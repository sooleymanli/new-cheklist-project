export class I18nService {
  translate(key: string, locale: string = 'az', params?: Record<string, string>): string {
    const lang = messages[locale] || messages['az'];
    let text = lang[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`{{${k}}}`, 'g'), v);
      });
    }
    return text;
  }

  getLocaleFromRequest(request: any): string {
    const acceptLang = request?.headers?.['accept-language'] || 'az';
    const lang = acceptLang.split(',')[0].split('-')[0].trim();
    return ['az', 'en', 'ru'].includes(lang) ? lang : 'az';
  }
}

export const i18nService = new I18nService();
